  internal static class WindowLayoutEditorUtility
  {
    public static readonly (string label, float aspect)[] AspectPresets =
    {
      ("16:9", 16f / 9f), ("21:9", 21f / 9f), ("4:3", 4f / 3f), ("1:1", 1f), ("3:4", 3f / 4f), ("9:16", 9f / 16f), ("9:19.5", 9f / 19.5f)
    };

    /// <summary>Library used for an object: its layout root's library, otherwise the first library asset.</summary>
    public static WindowLayoutLibrary FindLibrary(Object context)
    {
      if (context is Component component)
      {
        var root = component.GetComponentInParent<WindowLayoutRoot>(true);
        if (root == null)
          root = FindRoots().FirstOrDefault(r => r.Library != null);
        if (root != null && root.Library != null)
          return root.Library;
      }

      string guid = AssetDatabase.FindAssets("t:WindowLayoutLibrary").FirstOrDefault();
      return guid != null ? AssetDatabase.LoadAssetAtPath<WindowLayoutLibrary>(AssetDatabase.GUIDToAssetPath(guid)) : null;
    }

    public static WindowLayoutRoot FindRoot(Component context)
    {
      var root = context != null ? context.GetComponentInParent<WindowLayoutRoot>(true) : null;
      return root != null ? root : FindRoots().FirstOrDefault();
    }

    public static IEnumerable<WindowLayoutRoot> FindRoots()
    {
      PrefabStage stage = PrefabStageUtility.GetCurrentPrefabStage();
      if (stage != null)
        foreach (WindowLayoutRoot root in stage.prefabContentsRoot.GetComponentsInChildren<WindowLayoutRoot>(true))
          yield return root;

      for (int i = 0; i < SceneManager.sceneCount; i++)
      {
        Scene scene = SceneManager.GetSceneAt(i);
        if (!scene.isLoaded)
          continue;
        foreach (GameObject go in scene.GetRootGameObjects())
          foreach (WindowLayoutRoot root in go.GetComponentsInChildren<WindowLayoutRoot>(true))
            yield return root;
      }
    }

    /// <summary>Writes a C# file with constants for every slot id next to the library asset.</summary>
    public static string GenerateConstants(WindowLayoutLibrary library)
    {
      string assetPath = AssetDatabase.GetAssetPath(library);
      string className = MakeIdentifier(library.name);
      string path = EditorUtility.SaveFilePanelInProject("Generate slot constants", className + "Slots", "cs",
        "Constants with the ids of every slot.", Path.GetDirectoryName(assetPath));
      if (string.IsNullOrEmpty(path))
        return null;

      className = MakeIdentifier(Path.GetFileNameWithoutExtension(path));
      var builder = new StringBuilder();
      builder.AppendLine("// <auto-generated> Generated from " + Path.GetFileName(assetPath) + " by Windows System. </auto-generated>");
      builder.AppendLine();
      builder.AppendLine("public static class " + className);
      builder.AppendLine("{");
      var used = new HashSet<string>();
      foreach (WindowSlot slot in library.Slots.Where(s => s != null))
      {
        string identifier = MakeIdentifier(slot.name);
        string unique = identifier;
        for (int i = 2; !used.Add(unique); i++)
          unique = identifier + i;
        builder.AppendLine($"  /// <summary>{slot.name}</summary>");
        builder.AppendLine($"  public const string {unique} = \"{slot.Id}\";");
      }

      builder.AppendLine("}");
      File.WriteAllText(path, builder.ToString());
      AssetDatabase.ImportAsset(path);
      return path;
    }

    private static string MakeIdentifier(string text)
    {
      var builder = new StringBuilder();
      bool upper = true;
      foreach (char c in text ?? string.Empty)
      {
        if (char.IsLetterOrDigit(c))
        {
          builder.Append(upper ? char.ToUpperInvariant(c) : c);
          upper = false;
        }
        else
        {
          upper = true;
        }
      }

      if (builder.Length == 0 || char.IsDigit(builder[0]))
        builder.Insert(0, '_');
      return builder.ToString();
    }
  }

  /// <summary>Edit Mode preview of slots and tilings with an exact revert.</summary>
  [InitializeOnLoad]
  internal static class WindowLayoutEditorPreview
  {
    private struct Snapshot
    {
      public Vector2 AnchorMin, AnchorMax, OffsetMin, OffsetMax;
    }

    private static readonly Dictionary<RectTransform, Snapshot> Backup = new();

    static WindowLayoutEditorPreview()
    {
      EditorApplication.playModeStateChanged += _ => Backup.Clear();
      EditorSceneManager.sceneClosing += (_, _) => Backup.Clear();
    }

    public static bool HasPreview => Backup.Count > 0;

    public static void PreviewSlot(WindowLayoutRoot root, IEnumerable<WindowBase> windows, WindowSlot slot)
    {
      Rect rect = root.GetSlotRect(slot);
      foreach (WindowBase window in windows)
        Apply(root, window, rect, $"Preview slot '{slot.name}'");
    }

    public static void PreviewTiling(WindowLayoutRoot root, IReadOnlyList<WindowBase> windows, WindowTilingMode mode)
    {
      var rects = new List<Rect>();
      root.ComputeTiling(mode, windows.Count, rects);
      for (int i = 0; i < windows.Count; i++)
        Apply(root, windows[i], rects[i], $"Preview tiling '{mode}'");
    }

    public static void Revert()
    {
      foreach (KeyValuePair<RectTransform, Snapshot> entry in Backup)
      {
        if (entry.Key == null)
          continue;
        Undo.RecordObject(entry.Key, "Revert Window Layout Preview");
        entry.Key.anchorMin = entry.Value.AnchorMin;
        entry.Key.anchorMax = entry.Value.AnchorMax;
        entry.Key.offsetMin = entry.Value.OffsetMin;
        entry.Key.offsetMax = entry.Value.OffsetMax;
        PrefabUtility.RecordPrefabInstancePropertyModifications(entry.Key);
      }

      Backup.Clear();
    }

    public static void Keep() => Backup.Clear();

    private static void Apply(WindowLayoutRoot root, WindowBase window, Rect rect, string undoName)
    {
      RectTransform target = window != null ? window.RectTransform : null;
      if (target == null)
        return;

      if (!Backup.ContainsKey(target))
        Backup[target] = new Snapshot
        {
          AnchorMin = target.anchorMin, AnchorMax = target.anchorMax, OffsetMin = target.offsetMin, OffsetMax = target.offsetMax
        };

      Undo.RecordObject(target, undoName);
      WindowLayoutMath.ApplyRect(target, root.RectTransform, rect);
      PrefabUtility.RecordPrefabInstancePropertyModifications(target);
    }
  }
